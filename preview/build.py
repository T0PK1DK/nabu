#!/usr/bin/env python3
"""Build Nabu's page from preview/template.html.

Writes three copies:
- preview/nabu.html: the claude.ai artifact, where Claude writes the answers.
- static/app.html: served by python3 app.py, answers from /api/answer.
- worker/src/page.js: served by the Cloudflare Worker, answers from /api/answer.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
seed = json.dumps(json.loads((ROOT / "seed.json").read_text(encoding="utf-8")), ensure_ascii=False).replace("</", "<\\/")
body = (ROOT / "preview" / "template.html").read_text(encoding="utf-8").replace("__SEED__", seed)
(ROOT / "preview" / "nabu.html").write_text(body, encoding="utf-8")

page = (
    '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
    '<meta name="description" content="Nabu: a cited answer engine and encyclopedia.">\n'
    '<meta name="theme-color" content="#fbfaf6" media="(prefers-color-scheme: light)">\n'
    '<meta name="theme-color" content="#171818" media="(prefers-color-scheme: dark)">\n'
    "</head>\n<body>\n" + body + "\n</body>\n</html>\n"
)
(ROOT / "static" / "app.html").write_text(page, encoding="utf-8")
(ROOT / "worker" / "src" / "page.js").write_text(
    "// Generated by preview/build.py. Edit preview/template.html instead.\nexport default " + json.dumps(page, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print("wrote preview/nabu.html, static/app.html, worker/src/page.js")
